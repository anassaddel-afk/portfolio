function rowsOf(tools: string[]) {
  const design = tools.indexOf("Illustrator");
  const data = tools.indexOf("CleverTap");
  if (design !== -1 && data !== -1) {
    return [tools.slice(0, design + 1), tools.slice(design + 1, data + 1), tools.slice(data + 1)];
  }
  const n = Math.ceil(tools.length / 3);
  return [tools.slice(0, n), tools.slice(n, n * 2), tools.slice(n * 2)];
}

function ToolItems({ tools }: { tools: string[] }) {
  return tools.map((tool, i) => (
    <li key={tool} className="flex items-center gap-x-[0.35em]">
      <span className="inline-flex items-center gap-[0.32em] transition-colors duration-300 hover:text-accent">
        <ToolLogo name={tool} />
        {tool}
      </span>
      {i < tools.length - 1 ? (
        <span aria-hidden className="text-subtle">
          /
        </span>
      ) : null}
    </li>
  ));
}

export function ToolboxList({ tools, size = "display" }: { tools: string[]; size?: "display" | "compact" }) {
  if (size === "compact") {
    return (
      <ul className="flex flex-wrap items-center gap-x-4 gap-y-2 text-small">
        <ToolItems tools={tools} />
      </ul>
    );
  }

  return (
    <ul className="mt-12 flex flex-col gap-y-3 text-[length:clamp(1.2rem,2.15vw,2.05rem)] font-medium leading-(--lh-h3)">
      {rowsOf(tools).map((row) => (
        <li key={row[0]}>
          <ul className="flex flex-wrap items-center gap-x-[0.45em] gap-y-2 lg:flex-nowrap">
            <ToolItems tools={row} />
          </ul>
        </li>
      ))}
    </ul>
  );
}
